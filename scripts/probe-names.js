/** 判断一个 2-3 字中文串是否是「疑似人名」 */
function looksLikeName (span) {
  if (!span) return false
  if (BLOCK_WORDS.indexOf(span) !== -1) return false

  const hasCompound = COMPOUND_SURNAMES.some(function (s) { return span.indexOf(s) === 0 })
  let surname = null
  let rest = ''

  if (hasCompound) {
    surname = COMPOUND_SURNAMES.find(function (s) { return span.indexOf(s) === 0 })
    rest = span.slice(surname.length)
  } else {
    const first = span[0]
    if (SURNAMES.indexOf(first) === -1) return false
    surname = first
    rest = span.slice(1)
  }

  if (!rest) return false
  if (rest.length > 2) return false
  // 名字部分每个字都必须是常用名字用字
  for (const ch of rest) {
    if (!NAME_CHARS.has(ch)) return false
  }
  return true
}

